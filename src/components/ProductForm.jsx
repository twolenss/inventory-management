import { useState, useEffect } from "react";
import { useNavigate } from "react-router-dom";
import Swal from "sweetalert2";
import { 
  ArrowLeft, 
  Package, 
  Tag,  
  DollarSign,
  Box, 
  Truck, 
  FileText,
  Save,
  X,
  AlertCircle
} from "lucide-react";

// Separate InputField component outside of ProductForm to prevent recreation
const InputField = ({ id, label, icon: Icon, type = "text", value, onChange, placeholder, error, ...props }) => (
  <div className="space-y-2">
    <label htmlFor={id} className="flex items-center gap-2 text-sm font-medium text-secondary-text">
      <Icon className="h-4 w-4" />
      {label}
    </label>
    {type === "textarea" ? (
      <textarea
        id={id}
        value={value}
        onChange={onChange}
        placeholder={placeholder}
        className={`w-full rounded-xl border ${error ? 'border-red-300' : 'border-border'} bg-background px-4 py-3 text-primary-text outline-none transition focus:border-accent focus:ring-2 focus:ring-accent/20`}
        rows="4"
        {...props}
      />
    ) : (
      <input
        id={id}
        type={type}
        value={value}
        onChange={onChange}
        placeholder={placeholder}
        className={`w-full rounded-xl border ${error ? 'border-red-300' : 'border-border'} bg-background px-4 py-3 text-primary-text outline-none transition focus:border-accent focus:ring-2 focus:ring-accent/20`}
        {...props}
      />
    )}
    {error && (
      <p className="flex items-center gap-1 text-sm text-red-500">
        <AlertCircle className="h-3 w-3" />
        {error}
      </p>
    )}
  </div>
);

function ProductForm({ mode = "add", initialData = null, onSubmit }) {
  // COMMENT: PROJECT ONLY ACCEPTS THREE DATA FIELDS: id, name, and price
  // Keeping state for all fields but will only submit name and price
  // id is auto-generated by JSON server
  const [ id , setId ] = useState(initialData?.id || ""); // COMMENT: Not submitted - auto-generated
  const [name, setName] = useState("");
  //const [desc, setDesc] = useState("");  COMMENT: Not submitted - kept for UI only
  //const [category, setCategory] = useState(""); // COMMENT: Not submitted - kept for UI only
  const [price, setPrice] = useState("");
  //const [stock, setStock] = useState(""); // COMMENT: Not submitted - kept for UI only
  //const [supplier, setSupplier] = useState(""); // COMMENT: Not submitted - kept for UI only
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [errors, setErrors] = useState({});
  const navigate = useNavigate();

  const validateForm = () => {
    const newErrors = {};
    
    // COMMENT: Only validating name and price since only these are submitted
    if (!name.trim()) newErrors.name = "Product name is required";
    if (!price || Number(price) <= 0) newErrors.price = "Price must be greater than 0";
    
    // COMMENT: Not validating other fields since they're not submitted
    // if (!desc.trim()) newErrors.desc = "Description is required";
    // if (!category.trim()) newErrors.category = "Category is required";
    // if (!stock || Number(stock) < 0) newErrors.stock = "Stock cannot be negative";
    // if (!supplier.trim()) newErrors.supplier = "Supplier is required";
    
    return newErrors;
  };

  useEffect(() => {
    if (mode === "edit" && initialData) {
      setName(initialData.name || "");
      setPrice(initialData.price || "");
      // COMMENT: Not setting other fields from initial data since they're not in the model
      // setDesc(initialData.description || "");
      // setCategory(initialData.category || "");
      // setStock(initialData.stock || "");
      // setSupplier(initialData.supplier || "");
    }
  }, [mode, initialData]);

  // Check if form has any input
  const hasFormInput = () => {
    // COMMENT: Only checking name and price since other fields are not submitted
    return name.trim() || price.trim();
    // Original: return name.trim() || desc.trim() || category.trim() || price.trim() || stock.trim() || supplier.trim();
  };

  // Handle cancel/back navigation
  const handleCancel = () => {
    if (hasFormInput()) {
      Swal.fire({
        title: "Discard changes?",
        text: "You have unsaved changes. Are you sure you want to leave?",
        icon: "warning",
        showCancelButton: true,
        confirmButtonColor: "#d33",
        cancelButtonColor: "#6c757d",
        confirmButtonText: "Yes, discard",
        cancelButtonText: "No, stay"
      }).then((result) => {
        if (result.isConfirmed) {
          navigate("/products");
        }
      });
    } else {
      navigate("/products");
    }
  };

  async function handleSubmit(e) {
    e.preventDefault();
    
    const validationErrors = validateForm();
    if (Object.keys(validationErrors).length > 0) {
      setErrors(validationErrors);
      return;
    }
    
    setErrors({});
    setIsSubmitting(true);

    if (!onSubmit) {
      setIsSubmitting(false);
      return;
    }

    // COMMENT: Creating data object with ONLY name and price
    // Other fields (desc, category, stock, supplier) are commented out
    const data = {
      name: name.trim(),
      price: Number(price),
      // COMMENT: Following fields are not included since project only accepts id, name, price
      // description: desc.trim(),
      // category: category.trim(),
      // stock: Number(stock),
      // supplier: supplier.trim(),
    };

    console.log("Submitting form data:", data);

    try {
      // Call the onSubmit prop function
      await onSubmit(data);

      // Show success message
      await Swal.fire({
        title: "Success!",
        text: `Product ${mode === "add" ? "added" : "updated"} successfully.`,
        icon: "success",
        confirmButtonColor: "#3085d6",
      });

      // Clear form only on success (for add mode)
      if (mode === "add") {
        setName("");
        setPrice("");
        // COMMENT: Not clearing other fields since they're not part of the model
        // setDesc("");
        // setCategory("");
        // setStock("");
        // setSupplier("");
      }
      
      // Navigate back to products page
      navigate("/products");
      
    } catch (error) {
      console.error("Form submission error:", error);
      await Swal.fire({
        title: "Error!",
        text: error.message || "Failed to save product. Please try again.",
        icon: "error",
        confirmButtonColor: "#d33",
      });
    } finally {
      setIsSubmitting(false);
    }
  }

  const isAddMode = mode === "add";
  const buttonText = isAddMode ? "Add Product" : "Update Product";
  const pageTitle = isAddMode ? "Add Product" : "Edit Product";

  return (
    <div className="mx-auto max-w-2xl">
      <div className="mb-8 flex items-center justify-between">
        <div className="flex items-center gap-4">
          <button
            onClick={handleCancel}
            className="inline-flex items-center gap-2 rounded-lg border border-border bg-surface px-4 py-2 text-sm font-medium text-secondary-text transition hover:bg-border"
          >
            <ArrowLeft className="h-4 w-4" />
            Back to Inventory
          </button>
          <div>
            <h1 className="text-2xl font-bold text-primary-text">{pageTitle}</h1>
            <p className="text-sm text-secondary-text">
              {isAddMode ? "Fill in product details" : "Update product information"}
            </p>
            {/* COMMENT: Note about simplified data structure */}
            <p className="mt-1 text-xs text-secondary-text/70">
              Note: Only name and price are saved (id is auto-generated)
            </p>
          </div>
        </div>
      </div>

      <form onSubmit={handleSubmit} className="rounded-2xl bg-surface p-6 shadow-lg ring-1 ring-border/50 sm:p-8">
        <div className="mb-8 grid grid-cols-1 gap-6 sm:grid-cols-2">
          <InputField
            id="name"
            label="Product Name"
            icon={Package}
            type="text"
            value={name}
            onChange={(e) => setName(e.target.value)}
            placeholder="e.g., Premium Wireless Headphones"
            error={errors.name}
            required
          />

          {/* COMMENT: Category field - visible but data not submitted */}
          <InputField
            id="category"
            label="Category (Not Saved)"
            icon={Tag}
            type="text"
            value={category}
            onChange={(e) => setCategory(e.target.value)}
            placeholder="e.g., Electronics, Furniture"
            // error={errors.category} // COMMENT: Not validating since not submitted
            // required // COMMENT: Not required since not submitted
          />

          <InputField
            id="price"
            label="Price"
            icon={DollarSign}
            type="number"
            value={price}
            onChange={(e) => setPrice(e.target.value)}
            placeholder="0.00"
            min="0"
            step="0.01"
            error={errors.price}
            required
          />

          {/* COMMENT: Stock field - visible but data not submitted */}
          <InputField
            id="stock"
            label="Stock Quantity (Not Saved)"
            icon={Box}
            type="number"
            value={stock}
            onChange={(e) => setStock(e.target.value)}
            placeholder="Enter quantity"
            min="0"
            // error={errors.stock} // COMMENT: Not validating since not submitted
            // required // COMMENT: Not required since not submitted
          />

          {/* COMMENT: Supplier field - visible but data not submitted */}
          <InputField
            id="supplier"
            label="Supplier (Not Saved)"
            icon={Truck}
            type="text"
            value={supplier}
            onChange={(e) => setSupplier(e.target.value)}
            placeholder="Supplier name"
            // error={errors.supplier} // COMMENT: Not validating since not submitted
            // required // COMMENT: Not required since not submitted
          />
        </div>

        {/* COMMENT: Description field - visible but data not submitted */}
        <InputField
          id="desc"
          label="Description (Not Saved)"
          icon={FileText}
          type="textarea"
          value={desc}
          onChange={(e) => setDesc(e.target.value)}
          placeholder="Describe the product features, specifications, and other details..."
          // error={errors.desc} // COMMENT: Not validating since not submitted
          // required // COMMENT: Not required since not submitted
        />

        <div className="mt-8 flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-end">
          <button
            type="button"
            onClick={handleCancel}
            className="inline-flex items-center justify-center gap-2 rounded-lg border border-border bg-surface px-5 py-3 font-medium text-secondary-text transition hover:bg-border sm:order-2"
          >
            <X className="h-4 w-4" />
            Cancel
          </button>
          <button
            type="submit"
            disabled={isSubmitting}
            className="inline-flex items-center justify-center gap-2 rounded-lg bg-gradient-to-r from-accent to-[#e4b521] px-6 py-3 font-medium text-primary-text transition-all hover:shadow-lg hover:scale-[1.02] disabled:opacity-70 disabled:cursor-not-allowed"
          >
            <Save className="h-4 w-4" />
            {isSubmitting ? (
              <>
                <span className="inline-block h-4 w-4 animate-spin rounded-full border-2 border-primary-text border-t-transparent"></span>
                Processing...
              </>
            ) : (
              buttonText
            )}
          </button>
        </div>
      </form>

      {/* Form Guidelines - Updated with comments */}
      <div className="mt-8 grid grid-cols-1 gap-4 sm:grid-cols-3">
        <div className="rounded-xl bg-blue-50 p-4 ring-1 ring-blue-100">
          <div className="flex items-center gap-3">
            <div className="rounded-lg bg-blue-100 p-2">
              <Package className="h-5 w-5 text-blue-600" />
            </div>
            <div>
              <p className="text-sm font-medium text-blue-800">Required Fields</p>
              <p className="text-xs text-blue-700">Only name and price are saved</p>
            </div>
          </div>
        </div>
        
        <div className="rounded-xl bg-amber-50 p-4 ring-1 ring-amber-100">
          <div className="flex items-center gap-3">
            <div className="rounded-lg bg-amber-100 p-2">
              <AlertCircle className="h-5 w-5 text-amber-600" />
            </div>
            <div>
              <p className="text-sm font-medium text-amber-800">Note</p>
              <p className="text-xs text-amber-700">Other fields are visible but not saved</p>
            </div>
          </div>
        </div>
        
        <div className="rounded-xl bg-green-50 p-4 ring-1 ring-green-100">
          <div className="flex items-center gap-3">
            <div className="rounded-lg bg-green-100 p-2">
              <DollarSign className="h-5 w-5 text-green-600" />
            </div>
            <div>
              <p className="text-sm font-medium text-green-800">Data Structure</p>
              <p className="text-xs text-green-700">Products: id, name, price only</p>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}

export default ProductForm;